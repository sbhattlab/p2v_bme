def table_representatives(results: Path) -> dict[str, list[dict] | str]:
    """Builds Table S14 (representative_sensitivity): results -> {representative_sensitivity.tex}.

    Per dataset, size and cap P: RF to the true tree, the scored BME length minus that of the P = 64 tree of the same
    replicate, RF to that tree, and the search time (starting tree and rounds, no branch lengths).
    """
    runs = our_runs(results, "representatives")
    reference = {(r["set"], r["n"], r["rep"]): r for r in runs if r["cap"] == 64}

    def cell(values: list[float], decimals: int) -> str:
        values = [v for v in values if v != ""]
        if not values:
            return "--"
        # mean and SD to 3 decimals first, as the sweep's summary printed them, then to the cell's decimals
        if len(values) == 1:
            return f"${round(values[0], 3):.{decimals}f}$"
        return f"${round(mean(values), 3):.{decimals}f} \\pm {round(stdev(values), 3):.{decimals}f}$"

    lines = []
    previous = None
    for tag, label in DATASETS.items():
        for n in sorted({r["n"] for r in runs if r["set"] == tag}):
            for cap in sorted(
                {r["cap"] for r in runs if r["set"] == tag and r["n"] == n}
            ):
                group = [
                    r for r in runs if (r["set"], r["n"], r["cap"]) == (tag, n, cap)
                ]
                ref = cap == 64
                delta = [
                    r["scored_length"] - reference[(tag, n, r["rep"])]["scored_length"]
                    for r in group
                    if (tag, n, r["rep"]) in reference and r["scored_length"] != ""
                ]
                time = [r["topology_time_s"] for r in group]
                if previous is not None and (tag, n) != previous:
                    lines.append(r"\addlinespace")
                previous = (tag, n)
                lines.append(
                    " & ".join(
                        [
                            label,
                            f"{n:,}",
                            str(cap),
                            cell([r["rf_pct"] for r in group], 3),
                            "ref." if ref else cell(delta, 3),
                            (
                                "ref."
                                if ref
                                else cell([r["rf_vs_cap64_pct"] for r in group], 3)
                            ),
                            cell(time, 1 if mean(time) < 100 else 0),
                        ]
                    )
                    + r"\\"
                )
    caption = (
        r"\textbf{Sensitivity to the cap on representatives.} Each run uses the recorded configuration "
        r"(sample-and-place start, eight rounds, tolerance stop) with only the cap $P$ changed; $P=64$ is the recorded "
        r"setting and the reference row. Five replicates (mean $\pm$ s.d.) at $10^4$ and $10^5$ leaves, one at "
        r"$10^6$. $\Delta L$ is the BME length of the output tree minus that of the $P=64$ tree from the same "
        r"replicate, both scored by the independent evaluator: exactly at $10^4$ leaves, and under a common cap of "
        r"$1{,}024$ representatives at $10^5$ and $10^6$ leaves, where exact scoring exceeds host memory. RF versus "
        r"$P=64$ is the Robinson--Foulds distance between the two trees from the same seed. Times are for "
        + hardware(runs)
        + r", the configuration of every other Phylo2VecME result."
    )
    tex = "\n".join(
        [
            HEAD.rstrip("\n"),
            r"\begin{table}[htbp]",
            r"\centering\small",
            r"\setlength{\tabcolsep}{2.5pt}",
            r"\caption{" + caption + "}",
            r"\label{tab:representative_sensitivity}",
            r"\begin{tabular}{@{}llrrrrr@{}}",
            r"\toprule",
            r"Dataset & $N$ & $P$ & RF to truth (\%) & $\Delta L$ vs $P{=}64$ & RF vs $P{=}64$ (\%) & Time (s)\\",
            r"\midrule",
            *lines,
            r"\bottomrule",
            r"\end{tabular}",
            r"\end{table}",
            "",
        ]
    )
    return {"representative_sensitivity.tex": tex}


def table_fastme(results: Path) -> dict[str, list[dict] | str]:
    """Builds Table S1 (fastme): results -> {fastme.tex}."""
    rows = read_jsonl(results / "fastme" / "cases.jsonl")
    names = {
        "jc10k": "JC",
        "jc1m": "JC subsets",
        "rnasim": "RNASim",
        "rna1m": "RNASim subsets",
    }
    order = list(names)
    ppm = 1e6

    def pm(xs: list[float], d: int, sign: bool = False) -> str:
        f = f"{{:{'+' if sign else ''},.{d}f}}"
        mu = f.format(mean(xs))
        if mu in ("+" + f"{0:.{d}f}", "-" + f"{0:.{d}f}"):
            mu = f"{0:.{d}f}"
        cell = f"${mu} \\pm {stdev(xs):,.{d}f}$" if len(xs) > 1 else f"${mu}$"
        return cell.replace(",", "{,}")

    def panel(arm: str) -> list[str]:
        groups: dict[tuple[str, int], list[dict]] = {}
        for r in rows:
            if arm in r:
                groups.setdefault((r["tag"], r["n"]), []).append(r[arm])
        body, last = [], None
        for (tag, n), a in sorted(
            groups.items(), key=lambda kv: (order.index(kv[0][0]), kv[0][1])
        ):
            rel = [ppm * x["rel_diff"] for x in a]
            share = 100 * sum(x["L"] <= x["L_fastme"] * (1 + 1e-12) for x in a) / len(a)
            spr = [ppm * max(0.0, x["spr"]["rel_gain"]) for x in a]
            tf = [x["fastme_wall_s"] for x in a if x["fastme_wall_s"] is not None]
            tp = [x["solver"]["wall_s"] for x in a]
            if last not in (None, tag):
                body.append(r"\addlinespace")
            last = tag
            body.append(
                f"{names[tag]} & {n:,} & {len(a)} & {pm(rel, 1, True)} & {share:.0f} & "
                f"{pm([x['rf_truth_fastme'] for x in a], 2)} & {pm([x['rf_truth'] for x in a], 2)} & "
                f"{pm(spr, 2)} & {pm(tf, 0)} & {pm(tp, 2)}\\\\"
            )
        return body

    solvers = [
        r[arm]["solver"]
        for r in rows
        for arm in ("sample", "rand", "polish")
        if arm in r
    ]
    hw = gpus(
        one({s["n_gpus"] for s in solvers}, "GPU counts"),
        short_gpu(one({s["gpu_name"] for s in solvers}, "GPUs")),
    )
    caption = (
        r"\textbf{\method\ and FastME.} Both programs solve exactly the same objective function: minimising BME on "
        r"the same distance matrix. The length of every output tree is recomputed in double precision from the full "
        r"distance matrix by a separate program. `Ours' is \method. The length difference is (\method\ $-$ "
        r"FastME)/FastME reported in parts per million (ppm), mean $\pm$ s.d. over the replicates. Ours $\le$ FastME "
        r"(\%) gives the share of replicates in which the \method\ tree is at least as short. RF is the "
        r"Robinson--Foulds error against the true tree. SPR gain is the further relative shortening of the \method\ "
        r"tree by an exhaustive SPR search. Running times for FastME are for a single run on one CPU thread, which in "
        r"\textbf{a} is BIONJ followed by one round of NNI and SPR, although its trees come from repeating that run to "
        r"convergence. Times for \method\ are for "
        + hw
        + r". Subsets are random draws from the $10^6$-sequence "
        r"alignments. \textbf{a}, each program's own starting tree (FastME: BIONJ, then NNI and SPR to convergence; "
        r"\method: sample-and-place). \textbf{b}, the same random starting tree."
    )
    head = (
        r" & & & Length diff. & Ours $\le$ & \multicolumn{2}{c}{RF (\%)} & SPR gain & \multicolumn{2}{c}{Time (s)}\\"
        "\n"
        r"\cmidrule(lr){6-7}\cmidrule(l){9-10}"
        "\n"
        r"Dataset & $N$ & Replicates & (ppm) & FastME (\%) & FastME & Ours & (ppm) & FastME & Ours\\"
    )
    lines = [
        HEAD.rstrip("\n"),
        r"\begin{table}[htbp]",
        r"\centering\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        f"\\caption{{{caption}}}",
        r"\label{tab:fastme}",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{@{}llrrrrrrrr@{}}",
        r"\toprule",
        head,
    ]
    for letter, arm in (("a", "sample"), ("b", "rand")):
        lines += [
            r"\midrule",
            f"\\multicolumn{{10}}{{@{{}}l}}{{\\textbf{{{letter}}}}}\\\\",
        ] + panel(arm)
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
    return {"fastme.tex": "\n".join(lines) + "\n"}


