                mine = ours[key][(ours[key]["set"] == tag) & (ours[key]["n"] == 10000)]
                columns = ["time_s", "rf_pct", "cpu_threads", "gpu_count", "source_path"]
                runs += [(label, method, *r) for r in mine[columns].itertuples(index=False)]
