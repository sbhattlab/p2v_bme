def write_tsv(path: Path, rows: list[dict]) -> None:
    """Writes rows as a tab-separated file with a header: (path, rows) -> None."""
    with path.open("w", newline="") as fh:
        writer = DictWriter(
            fh, fieldnames=list(rows[0]), delimiter="\t", lineterminator="\n"
        )
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    parser = ArgumentParser(
        description=__doc__, formatter_class=RawDescriptionHelpFormatter
    )
    parser.add_argument("--results-dir", type=Path, default=Path(DEFAULT_RESULTS_DIR))
    parser.add_argument("--tables-dir", type=Path, default=Path(DEFAULT_TABLES_DIR))
    parser.add_argument(
        "--tables",
        nargs="+",
        choices=list(TABLES),
        default=list(TABLES),
        metavar="TABLE",
        help=f"tables to write (default: all): {', '.join(TABLES)}",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="replace tables and data files that exist",
    )
    args = parser.parse_args()

    args.tables_dir.mkdir(parents=True, exist_ok=True)
    skipped = []
    for name in args.tables:
        try:
            outputs = TABLES[name](args.results_dir)
        except MissingResults as missing:
            skipped.append(name)
            print(f"make_tables: {name}: skipped, missing {missing}", file=stderr)
            continue
        written = []
        for file, content in outputs.items():
            path = args.tables_dir / file
            if path.exists() and not args.overwrite:
                continue
            if isinstance(content, str):
                path.write_text(content)
            else:
                write_tsv(path, content)
            written.append(file)
        kept = len(outputs) - len(written)
        print(
            f"make_tables: {name}: wrote {', '.join(written) or 'nothing'}"
            + (f" ({kept} kept, see --overwrite)" if kept else "")
        )
    if skipped:
        print(
            f"make_tables: skipped for missing results: {', '.join(skipped)}",
            file=stderr,
        )


if __name__ == "__main__":
    main()
