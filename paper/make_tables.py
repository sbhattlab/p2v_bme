def optional(read, results: Path) -> list[dict]:
    """Reads comparison runs that a table can do without: (reader, results) -> its records, or none."""
    try:
        return read(results)
    except MissingResults as missing:
        print(f"make_tables: no comparison runs: {missing}", file=stderr)
        return []


# ---- Formatting ----


def mean_sd(values: list) -> tuple[float | str, float | str]:
    """Averages values: -> (mean, sample SD); SD blank for one value, both blank for none."""
    return (
        (mean(values), stdev(values) if len(values) > 1 else "") if values else ("", "")
    )


def number(value: float | str, digits: int = 2) -> str:
    """Formats a number with thousands separators, or an em dash in LaTeX if missing."""
    return "---" if value == "" else f"{value:,.{digits}f}"


def grouped(value: int) -> str:
    """Formats an integer with LaTeX thousands separators, for math mode: 12345 -> '12{,}345'."""
    return f"{value:,}".replace(",", "{,}")


def estimate(row: dict, field: str) -> str:
    """Formats a mean with its sample SD when there is one: (row, field) -> LaTeX cell."""
    mu, sd = row[field + "_mean"], row[field + "_sd"]
    digits = 3 if field == "time_s" and mu < 1 else 2
    result = number(mu, digits)
    if sd == "":
        return result
    return (
        f"${result.replace(',', '{,}')} \\pm {number(sd, digits).replace(',', '{,}')}$"
    )


def seconds(x: float) -> str:
    """Formats a time: three significant figures below 100 s, whole seconds above."""
    if x < 1:
        return f"{x:.3f}"
    if x < 10:
        return f"{x:.2f}"
    if x < 100:
        return f"{x:.1f}"
    return f"{x:,.0f}"


def booktabs(
    name: str, caption: str, columns: str, header: str, body: list[str]
) -> str:
    """Builds a one-header booktabs table: (label suffix, caption, column spec, header, rows) -> LaTeX."""
    expected = len(columns.replace(" ", "")) - 1
    for line in [header, *body]:
        if line.count("&") != expected:
            raise ValueError(f"{name} requires {expected + 1} columns: {line}")
    return (
        HEAD + "\\begin{table}[htbp]\n\\centering\\small\n"
        f"\\caption{{{caption}}}\n\\label{{tab:nm_{name}}}\n"
        f"\\begin{{tabular}}{{{columns}}}\n\\toprule\n{header} \\\\\n\\midrule\n"
        + "\n".join(line + r" \\" for line in body)
        + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    )


