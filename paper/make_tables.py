# ---- Formatting ----


def mean_sd(values: list) -> tuple[float | str, float | str]:
    """Averages values: -> (mean, sample SD); SD blank for one value, both blank for none."""
    return (
        (statistics.mean(values), statistics.stdev(values) if len(values) > 1 else "")
        if values
        else ("", "")
    )


def blank(value) -> bool:
    """Tells a missing value: NA, NaN or an empty string."""
    return pd.isna(value) or value == ""


def mean_of(values: pd.Series):
    """Averages the values present, exactly as statistics.mean: values -> mean, NA if none."""
    values = values.dropna()
    return statistics.mean(values) if len(values) else pd.NA


def sd_of(values: pd.Series):
    """Gives the sample SD of the values present: values -> SD, NA for fewer than two."""
    values = values.dropna()
    return statistics.stdev(values) if len(values) > 1 else pd.NA


def number(value: float | str, digits: int = 2) -> str:
    """Formats a number with thousands separators, or an em dash if missing."""
    return "—" if blank(value) else f"{value:,.{digits}f}"


def power(exponent: int) -> str:
    """Writes a power of ten: 6 -> 10⁶."""
    return "10" + str(exponent).translate(SUPERSCRIPT)


def grouped(value: int) -> str:
    """Formats an integer with thousands separators: 12345 -> '12,345'."""
    return f"{value:,}"


def estimate(row: dict, field: str) -> list[str]:
    """Formats a mean and its sample SD: (row, field) -> [mean, SD], the SD blank for one value."""
    mu, sd = row[field + "_mean"], row[field + "_sd"]
    digits = 3 if field == "time_s" and mu < 1 else 2
    return [number(mu, digits), "" if blank(sd) else number(sd, digits)]


def seconds(x: float) -> str:
    """Formats a time: three significant figures below 100 s, whole seconds above."""
    if x < 1:
        return f"{x:.3f}"
    if x < 10:
        return f"{x:.2f}"
    if x < 100:
        return f"{x:.1f}"
    return f"{x:,.0f}"


def markdown(caption: str, header: list[str], body: list, align: str) -> str:
    """Builds a Markdown table under its caption:
    (caption, column names, rows of cells, l or r per column) -> Markdown.

    A string in body starts a section: its title in bold, then the rows below it as a table of their own.
    """
    if len(align) != len(header):
        raise ValueError(f"{len(header)} columns for the alignment {align}")
    parts: list[str] = []
    rows: list[list[str]] = []

    def table() -> None:
        if rows:
            colalign = ["left" if a == "l" else "right" for a in align]
            parts.append(tabulate(rows, header, "pipe", colalign=colalign, disable_numparse=True))
            rows.clear()

    for item in body:
        if isinstance(item, str):
            table()
            parts.append(f"**{item}**")
        elif len(item) != len(header):
            raise ValueError(f"{len(header)} columns needed: {item}")
        else:
            rows.append(item)
    table()
    return HEAD + "\n" + caption + "\n\n" + "\n\n".join(parts) + "\n"


