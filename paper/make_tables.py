    pairs = int(rows["pairs"].iloc[0]) if "pairs" in rows else GTR_PAIRS
    replicates = 1 + int(rows["replicate"].max())
    true_rates = [x * 6.0 / sum(GTR_RATES) for x in GTR_RATES]
